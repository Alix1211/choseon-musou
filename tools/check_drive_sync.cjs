'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const source=fs.readFileSync('_new/m3_sync.js','utf8');
const main=fs.readFileSync('android/app/src/main/java/com/kane/choseonmusou/MainActivity.java','utf8');
const native=fs.readFileSync('android/app/src/main/java/com/kane/choseonmusou/SaveSyncManager.java','utf8');
const decide=fs.readFileSync('android/app/src/main/java/com/kane/choseonmusou/SaveSyncDecider.java','utf8');
const standard=fs.readFileSync('docs/standards/drive_save_sync.md','utf8');
assert(html.includes(source),'The live HTML must inline the same cloud sync source');
new vm.Script(source,{filename:'m3_sync.js'});
assert(standard.includes('기준은 "이 기기가 파일과 마지막으로 맞춘 버전"(baseT)'),'ARPG standard not retained');
assert(html.includes("window.CHOSEON_SYNC_CHECKING")&&html.includes("window.CHOSEON_SYNC_CONFLICT"),'screen save gates missing');
assert(html.includes("window.ChoseonCloud.onGameSaved()"),'game save hook missing');
assert(html.includes('S.t=Math.max(Date.now()'),'revision t must increment only on actual change');
assert(source.includes("createdAt:new Date().toISOString(),game"),'existing v0.8 bundle format changed');
assert(source.includes("onConflict(remote,local)")&&source.includes("csUseFile")&&source.includes("csUseLocal"),'conflict choice missing');
assert(source.includes("window.confirm(msg)"),'conflict selection must be confirmed');
assert(source.includes("flag('CHOSEON_SYNC_CONFLICT',true)"),'conflict must hold game saves');
assert(source.includes('setTimeout(()=>onSyncDone(),20000)'),'UI gate 20s must outlast native read 15s');
assert(source.includes("window.__noSave=1"),'apply must block old-save overwrite');
assert(source.includes("snapshot()"),'saving must send existing JSON bundle');
assert(native.includes('return SaveSyncDecider.decide(lt,rt,bt)'),'Native must use tested ARPG decide');
assert(native.includes('private long baseT()')&&native.includes('putLong("baseT",-1)'),'per-file baseT missing');
assert(native.includes('private String readDocumentTimed(')&&native.includes('private void writeDocument('),'SAF I/O missing');
assert(native.includes('private void requestSync(boolean gate)'),'startup/resume reconciliation missing');
assert(native.includes('if(!sessionSynced){requestSync(false);return;}'),'write before first sync forbidden');
const write=native.slice(native.indexOf('private void writeDocument('),native.indexOf('private void queueBackup('));
assert(!/\.cancel\s*\(/.test(write.replace(/\/\/[^\n]*/g,'')),'document writes must NEVER be cancelled');
const save=native.slice(native.indexOf('private void writeBackup('),native.indexOf('private void requestSync('));
assert(!save.includes('readDocument(')&&!save.includes('readDocumentTimed('),'ordinary save must write without reread');
assert(native.includes('JSONObject remote=parseRemote(raw)'),'empty/corrupt remote detection missing');
assert(native.includes('catch(Exception e)')&&native.includes('sessionSynced=false'),'read errors must not write');
assert(!main.includes('class SaveBridge')&&!native.includes('autoBackup(String json)'),'old blind backup must be removed');
assert(main.includes('sync.onResume()')&&source.includes("addEventListener('online'"),'return/reconnect sync missing');
assert(source.includes("onApplied(text)")&&source.includes('localStorage.setItem(KEY,obj.game)'),'apply must preserve exact stored game JSON');
assert(decide.includes('return SYNC_ASK'),'conflict handler missing');
console.log('PASS ARPG standard baseT sync wiring (static/UI hooks only; not device I/O).');
